import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const standaloneDir = resolve(root, '.next/standalone')

if (!existsSync(resolve(standaloneDir, 'server.js'))) {
  console.warn('prepare-standalone: skip (no .next/standalone/server.js — run npm run build first)')
  process.exit(0)
}

cpSync(resolve(root, 'public'), resolve(standaloneDir, 'public'), { recursive: true })
cpSync(resolve(root, '.next/static'), resolve(standaloneDir, '.next/static'), { recursive: true })

const runDir = resolve(standaloneDir, 'bin')
mkdirSync(runDir, { recursive: true })
writeFileSync(
  resolve(runDir, 'run.mjs'),
  `// Generated by scripts/prepare-standalone.mjs — do not edit by hand.
// Next standalone reads HOSTNAME for bind address; Zerops reserves that key in env.
process.env.HOSTNAME = '0.0.0.0'
await import(new URL('../server.js', import.meta.url).href)
`,
)
